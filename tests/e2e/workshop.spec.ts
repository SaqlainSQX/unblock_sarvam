import { test, expect, type Page } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
async function ask(page: Page, question: string, mac = false) {
  await page.goto('/w/kivi');
  await expect(page.getByRole('button', { name: 'Find my next step' })).toBeEnabled();
  await page.getByLabel('Your question', { exact: true }).fill(question);
  await page.getByLabel('Operating system', { exact: true }).selectOption(mac ? 'macos' : 'windows');
  await page.getByLabel('App distribution', { exact: true }).selectOption(mac ? 'public' : 'workshop');
  if (!mac) await page.getByLabel('Kivi version', { exact: true }).fill('1.9.6');
  await page.getByRole('button', { name: 'Find my next step' }).click();
  await expect(page.getByRole('heading', { name: 'Your requests' })).toBeVisible();
}
